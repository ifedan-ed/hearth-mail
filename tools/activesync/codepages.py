#!/usr/bin/env python3
"""Generate crates/activesync-proto/src/wbxml/codepages.rs from [MS-ASWBXML].

The WBXML code pages of Exchange ActiveSync are the tables of section
2.1.2.1 of Microsoft's "[MS-ASWBXML]: Exchange ActiveSync: WAP Binary XML
(WBXML) Algorithm". This reads the text of that document as `pdftotext
-layout` lays it out and writes every page's tags and tokens as Rust, so
the tables are never typed by hand:

    curl -fLo MS-ASWBXML.pdf \
      'https://officeprotocoldoc.z19.web.core.windows.net/files/MS-ASWBXML/%5bMS-ASWBXML%5d.pdf'
    pdftotext -layout MS-ASWBXML.pdf MS-ASWBXML.txt
    tools/activesync/codepages.py MS-ASWBXML.txt > crates/activesync-proto/src/wbxml/codepages.rs

The generated file names the document's version. A tag listed for older
protocol versions only (2.5, 12.x) is kept: the token is reserved either
way, and decoding it costs nothing.
"""
import re
import sys

# pdftotext starts each PDF page with a form feed, sometimes right before a
# heading.
text = open(sys.argv[1], encoding='utf-8').read().replace('\f', '\n')
version = re.search(r'\[MS-ASWBXML\] - (v\d{8})', text).group(1)
# The body starts after the table of contents: the second heading of page 0.
start = [m.start() for m in re.finditer(r'^2\.1\.2\.1\.1 +Code Page 0: AirSync', text, re.M)][-1]
end = text.index('\n2.1.3 ', start)  # 2.1.3 Processing Rules follows the tables
body = text[start:end]

pages = []
for m in re.finditer(r'^2\.1\.2\.1\.\d+ +Code Page (\d+): (\w+)\n(.*?)(?=^2\.1\.2\.1\.\d+ +Code Page|\Z)',
                     body, re.M | re.S):
    number, name, section = int(m.group(1)), m.group(2), m.group(3)
    tags = []
    for line in section.splitlines():
        # " Tag name   0x05   Versions"; a note may follow the name.
        t = re.match(r'^\s*([A-Za-z][A-Za-z0-9]*)\b.*?\s(0x[0-9A-Fa-f]{2})\s', line + ' ')
        if t:
            tags.append((int(t.group(2), 16), t.group(1)))
    pages.append((number, name, sorted(set(tags))))

assert [p[0] for p in pages] == list(range(26)), [p[0] for p in pages]
for number, name, tags in pages:
    tokens = [t for t, _ in tags]
    assert len(tokens) == len(set(tokens)), (name, tags)
    assert all(0x05 <= t <= 0x3F for t in tokens), (name, tags)

def const_name(tag):
    """SyncKey -> SYNC_KEY, MIMESupport -> MIME_SUPPORT, IMAddress2 -> IM_ADDRESS2."""
    name = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', tag)
    name = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', name)
    return name.upper()


def module_name(namespace):
    # `move` is a Rust keyword.
    name = namespace.lower()
    return 'r#move' if name == 'move' else name


for number, name, tags in pages:
    names = [const_name(t) for _, t in tags]
    assert len(names) == len(set(names)), (name, names)

out = sys.stdout
out.write(f'''/*
 * SPDX-FileCopyrightText: 2026 Hearth Mail
 *
 * SPDX-License-Identifier: AGPL-3.0-only
 */

//! The ActiveSync WBXML code pages, generated by tools/activesync/codepages.py
//! from [MS-ASWBXML] {version}, section 2.1.2.1. Do not edit by hand.
//!
//! `PAGES[n]` is code page `n`: its namespace name and its tags, sorted by
//! token, so a token is found by binary search and a name by a scan of one
//! page (at most 60 entries). The modules below name every tag as a
//! [`Tag`] constant (`airsync::SYNC_KEY`), so code never spells a token.

use super::Tag;

/// One code page: the XML namespace it stands for and its (token, tag) pairs.
pub struct CodePage {{
    pub namespace: &'static str,
    pub tags: &'static [(u8, &'static str)],
}}

pub static PAGES: [CodePage; {len(pages)}] = [
''')
for number, name, tags in pages:
    out.write(f'    // Code page {number}\n    CodePage {{\n        namespace: "{name}",\n        tags: &[\n')
    for token, tag in tags:
        out.write(f'            (0x{token:02X}, "{tag}"),\n')
    out.write('        ],\n    },\n')
out.write('];\n')
for number, name, tags in pages:
    if not tags:
        continue
    out.write(f'\n/// Code page {number}, `{name}`.\npub mod {module_name(name)} {{\n    use super::Tag;\n')
    for token, tag in tags:
        out.write(f'    pub const {const_name(tag)}: Tag = Tag::new({number}, 0x{token:02X});\n')
    out.write('}\n')
